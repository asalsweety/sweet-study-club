import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'

// Official Konkur 1405 questions (سازمان سنجش, Mordad 1405) checked against the
// initial official key. Explanations are Sweet Study's own. Writes migration 25.
const rows = JSON.parse(readFileSync(new URL('../content/learning/konkur-1405.json', import.meta.url), 'utf8'))
const digest = (value) => createHash('sha256').update(value).digest('hex').slice(0, 32)
const quote = (value) => value === null ? 'NULL' : typeof value === 'number' ? String(value) : `'${String(value).replaceAll("'", "''")}'`
const publishedAt = Date.parse('2026-11-23T00:00:00.000Z')

const packs = new Map()
for (const row of rows) {
  const { track, packId, packTitle, packAttribution, year, period, ...question } = row
  assert.equal(question.language, 'fa')
  assert.equal(question.options.length, 4)
  assert(Number.isInteger(question.correctIndex) && question.correctIndex >= 0 && question.correctIndex <= 3)
  assert.deepEqual(question.images, [])
  assert(['konkur', 'konkur-math', 'konkur-humanities'].includes(track), `Unexpected track ${track}`)
  if (!packs.has(packId)) packs.set(packId, { track, title: packTitle, attribution: packAttribution, year, period, questions: [] })
  const pack = packs.get(packId)
  assert.equal(pack.track, track)
  pack.questions.push(question)
}
assert.equal(new Set(rows.map((row) => row.key)).size, rows.length, 'Question keys must be unique')

let sql = '-- Official Konkur 1405 questions; generated by scripts/build-konkur-1405.mjs.\n'
for (const [id, pack] of [...packs].sort(([a], [b]) => a.localeCompare(b))) {
  sql += `INSERT INTO learning_packs (id,title,track,bank,provider,grade,year,period,available_at,is_sample,attribution,created_at) VALUES (${[id, pack.title, pack.track, 'national', 'konkur', 'konkur', pack.year, pack.period, publishedAt, 0, pack.attribution, publishedAt].map(quote).join(',')});\n`
  for (const question of pack.questions) {
    sql += `INSERT INTO learning_questions (id,pack_id,subject_id,chapter,difficulty,content) VALUES (${[digest(`${id}-${question.key}`), id, question.subjectId, question.chapter, question.difficulty, JSON.stringify(question)].map(quote).join(',')});\n`
  }
}
sql += "UPDATE system_metadata SET value = '25', updated_at = unixepoch() WHERE key = 'schema_version';\n"
writeFileSync(new URL('../migrations/0025_konkur_1405_questions.sql', import.meta.url), sql)
console.log(`${rows.length} questions in ${packs.size} packs → migrations/0025_konkur_1405_questions.sql`)
