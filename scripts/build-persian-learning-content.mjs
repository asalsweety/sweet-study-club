import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

// Migration 9 remains immutable. Archive its English library without deleting
// questions referenced by previous attempts, then publish the Persian snapshots.
const read = (name) => JSON.parse(readFileSync(new URL(`../content/learning/${name}`, import.meta.url), 'utf8'))
const native = read('persian-exams.json')
const biology = read('biology.json')
const localized = read('biology-fa.json')
const digest = (value) => createHash('sha256').update(value).digest('hex').slice(0, 32)
const groups = new Map()
const add = (key, metadata, question) => {
  if (!groups.has(key)) groups.set(key, { ...metadata, questions: [] })
  groups.get(key).questions.push(question)
}
const periodId = { 'اسفند': 'esfand', 'نوبت اول': 'first', 'نوبت دوم': 'second' }
const trackNames = { 'medical-basics': 'علوم پایه پزشکی', preinternship: 'پیش‌کارورزی', konkur: 'کنکور تجربی' }
const persianNumber = (number) => String(number).replace(/\d/g, (digit) => '۰۱۲۳۴۵۶۷۸۹'[Number(digit)])
for (const row of native) {
  const { track, year, period, questionNumber: _number, sourcePage: _page, ...question } = row
  assert(periodId[period], `Unknown exam period: ${period}`)
  const key = `persian-${track}-${year}-${periodId[period]}-${question.subjectId}`
  add(key, {
    title: `${trackNames[track]} ${persianNumber(year)} · ${period} · ${question.chapter}`,
    track, bank: 'national', provider: track === 'konkur' ? 'konkur' : 'national', year, period,
    attribution: `${question.source.name}. ${question.source.license}. کلید منبع حفظ شده؛ توضیح تشریحی و درجهٔ سختی تأییدشده در منبع موجود نیست.`,
  }, question)
}

// Only Persian textbook adaptations; retain the original option order and key.
const chapters = {
  3: ['مولکول‌های زیستی', 'biochemistry'], 4: ['ساختار سلول', 'histology'],
  5: ['غشا و جابه‌جایی مواد', 'physiology'], 10: ['چرخهٔ سلولی', 'genetics'],
  12: ['وراثت مندلی', 'genetics'], 14: ['ساختار و عملکرد DNA', 'genetics'],
}
for (const fa of localized.translations) {
  const row = biology.questions.find((question) => question.id === fa.id)
  assert(row, `Missing original exercise: ${fa.id}`)
  const [chapter, subject] = chapters[row.chapterNumber]
  for (const track of ['konkur', 'medical-basics', 'dental-basics', 'bachelor-medicine']) {
    if (track === 'dental-basics' && ['genetics', 'physiology'].includes(subject)) continue
    const subjectId = track === 'konkur' ? 'biology' : subject
    add(`persian-openstax-${track}-${subjectId}`, {
      title: 'زیست‌شناسی · تمرین‌های فارسی', track, bank: 'reference', provider: 'openstax', year: null, period: 'تمرین فارسی',
      attribution: 'زیست‌شناسی ۲ — کلارک، داگلاس و چوی / اوپن‌استکس. ترجمه و توضیح فارسی: سوئیت استادی. نسخهٔ ۲۰ دسامبر ۲۰۲۴، CC BY 4.0. تمرین کتاب درسی؛ سؤال رسمی ایران نیست.',
    }, {
      key: digest(`${row.module}-${row.id}`), subjectId, chapter, prompt: fa.prompt, options: fa.options,
      correctIndex: row.correctIndex, explanation: fa.explanation, difficulty: 'medium',
      topic: localized.topics[String(row.chapterNumber)], language: 'fa', images: [],
      source: { name: 'زیست‌شناسی ۲ اوپن‌استکس — ترجمه و توضیح فارسی سوئیت استادی',
        url: `https://github.com/openstax/osbooks-biology-bundle/blob/${biology.revision}/modules/${row.module}/index.cnxml#${row.id}`,
        license: 'CC-BY-4.0', questionId: `${row.module}#${row.id}`, revision: biology.revision },
    })
  }
}

const quote = (value) => value === null ? 'NULL' : typeof value === 'number' ? String(value) : `'${String(value).replaceAll("'", "''")}'`
const publishedAt = Date.parse('2026-11-02T00:00:00.000Z')
let sql = '-- Persian-only library; generated by scripts/build-persian-learning-content.mjs.\n'
sql += "UPDATE learning_packs SET is_active = 0 WHERE id LIKE 'reference-%';\n"
const packs = []
for (const [key, group] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
  assert.equal(new Set(group.questions.map((question) => question.key)).size, group.questions.length)
  for (let offset = 0; offset < group.questions.length; offset += 200) {
    const pack = { ...group, key: `${key}-${Math.floor(offset / 200) + 1}`, questions: group.questions.slice(offset, offset + 200) }
    packs.push(pack)
    sql += `INSERT INTO learning_packs (id,title,track,bank,provider,year,period,available_at,is_sample,attribution,created_at) VALUES (${[pack.key, pack.title, pack.track, pack.bank, pack.provider, pack.year, pack.period, publishedAt, 0, pack.attribution, publishedAt].map(quote).join(',')});\n`
    for (const question of pack.questions) {
      assert.equal(question.language, 'fa')
      assert.equal(question.options.length, 4)
      assert(Number.isInteger(question.correctIndex) && question.correctIndex >= 0 && question.correctIndex <= 3)
      for (const path of question.images) {
        assert(/^\/question-media\/[a-zA-Z0-9_-]+\.jpg$/.test(path))
        assert(existsSync(new URL(`../public${path}`, import.meta.url)), `Missing image: ${path}`)
      }
      // Separate statements stay below D1 SQL length/parameter limits.
      sql += `INSERT INTO learning_questions (id,pack_id,subject_id,chapter,difficulty,content) VALUES (${[digest(`${pack.key}-${question.key}`), pack.key, question.subjectId, question.chapter, question.difficulty, JSON.stringify(question)].map(quote).join(',')});\n`
    }
  }
}
sql += "UPDATE system_metadata SET value = '10', updated_at = unixepoch() WHERE key = 'schema_version';\n"
writeFileSync(new URL('../migrations/0010_persian_learning_content.sql', import.meta.url), sql)
const manifest = {
  sourceQuestions: native.length + localized.translations.length,
  nativePersianQuestions: native.length, persianTextbookTranslations: localized.translations.length,
  packs: packs.length, questionPlacements: packs.reduce((total, pack) => total + pack.questions.length, 0),
  tracks: Object.fromEntries([...new Set(packs.map((pack) => pack.track))].sort().map((track) => [track, packs.filter((pack) => pack.track === track).reduce((total, pack) => total + pack.questions.length, 0)])),
  nativeTracks: Object.fromEntries([...new Set(native.map((question) => question.track))].sort().map((track) => [track, native.filter((question) => question.track === track).length])),
  sourceHashes: { persianSnapshot: createHash('sha256').update(readFileSync(new URL('../content/learning/persian-exams.json', import.meta.url))).digest('hex'), biologyRevision: biology.revision },
}
writeFileSync(new URL('../content/learning/manifest.json', import.meta.url), `${JSON.stringify(manifest, null, 2)}\n`)
